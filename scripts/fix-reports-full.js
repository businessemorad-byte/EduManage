L('  const conversionRate = totalLeads > 0 ? Math.round((converted / totalLeads) * 100) : 0;');
L('');
L('  const newLeads = range.startDate ? leads.filter(l => new Date(l.createdAt) >= new Date(range.startDate!)).length : totalLeads;');
L('');
L('  const trialsCompleted = trials.filter(t => t.status === "COMPLETED").length;');
L('  const trialsEnrolled = trials.filter(t => t.status === "ENROLLED").length;');
L('  const trialConversion = trialsCompleted > 0 ? Math.round((trialsEnrolled / trialsCompleted) * 100) : 0;');
L('');
L('  return {');
L('    totalLeads, newLeads, totalAdmissions: admissions.length, converted, conversionRate,');
L('    leadsByStatus: Object.entries(leadsByStatus).map(([status, count]) => ({ status, count })),');
L('    admissionsByStatus: Object.entries(admissionsByStatus).map(([status, count]) => ({ status, count })),');
L('    totalTrials: trials.length, trialsCompleted, trialConversion,');
L('  };');
L('}');
