L('export type DateRange = { startDate?: string; endDate?: string };');
L('');
L('export function parseDateRange(sp: URLSearchParams): DateRange {');
L('  return { startDate: sp.get("startDate") ?? undefined, endDate: sp.get("endDate") ?? undefined };');
L('}');
L('');
L('function createdAtFilter(range: DateRange) {');
L('  if (!range.startDate && !range.endDate) return undefined;');
L('  return {');
L('    createdAt: {');
L('      ...(range.startDate ? { gte: new Date(range.startDate) } : {}),');
L('      ...(range.endDate ? { lte: new Date(range.endDate + "T23:59:59.999Z") } : {}),');
L('    },');
L('  };');
L('}');
L('');
L('function dateBetween(field: string, range: DateRange) {');
L('  if (!range.startDate && !range.endDate) return undefined;');
L('  return {');
L('    [field]: {');
L('      ...(range.startDate ? { gte: new Date(range.startDate) } : {}),');
L('      ...(range.endDate ? { lte: new Date(range.endDate + "T23:59:59.999Z") } : {}),');
L('    },');
L('  };');
L('}');
L('');
L('function archivedFilter() {');
L('  return { person: { status: { not: "ARCHIVED" as const } } };');
L('}');
