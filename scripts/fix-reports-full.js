L('  return { totalStudents, activeStudents, newStudentsThisMonth, totalStaff, totalGroups, totalSessions, totalLeads, totalAdmissions, attendanceRate, totalRevenue: totalPaid.toNumber(), totalOutstanding: totalOutstanding.toNumber() };');
