L('export async function getAttendanceReport(organizationId: string, range: DateRange) {');
L('  const where: Record<string, unknown> = { organizationId };');
L('  const adf = dateBetween("date", range);');
L('  if (adf) Object.assign(where, adf);');
L('');
L('  const records = await db.attendanceRecord.findMany({ where, include: { student: { include: { person: { select: { firstName: true, lastName: true } } } }, group: { select: { name: true } } } });');
L('');
L('  const total = records.length;');
L('  const present = records.filter(r => r.status === "PRESENT").length;');
L('  const absent = records.filter(r => r.status === "ABSENT").length;');
L('  const late = records.filter(r => r.status === "LATE").length;');
L('  const excused = records.filter(r => r.status === "EXCUSED").length;');
L('');
L('  const byGroup: Record<string, { total: number; present: number }> = {};');
L('  for (const r of records) {');
L('    const grp = r.group?.name || "Unknown";');
L('    if (!byGroup[grp]) byGroup[grp] = { total: 0, present: 0 };');
L('    byGroup[grp].total++;');
L('    if (r.status === "PRESENT") byGroup[grp].present++;');
L('  }');
L('');
L('  const byStudent: Record<string, { name: string; total: number; present: number; absent: number }> = {};');
L('  for (const r of records) {');
L('    const sid = r.studentId;');
L('    if (!byStudent[sid]) byStudent[sid] = { name: r.student.person.firstName + " " + r.student.person.lastName, total: 0, present: 0, absent: 0 };');
L('    byStudent[sid].total++;');
L('    if (r.status === "PRESENT") byStudent[sid].present++;');
L('    if (r.status === "ABSENT") byStudent[sid].absent++;');
L('  }');
L('');
L('  const frequentAbsences = Object.values(byStudent).filter(s => s.absent >= 3).sort((a, b) => b.absent - a.absent).slice(0, 20);');
L('');
L('  const byDayMap: Record<string, { total: number; present: number }> = {};');
L('  for (const r of records) {');
L('    const day = new Date(r.date).toLocaleDateString("en-US", { weekday: "long" });');
L('    if (!byDayMap[day]) byDayMap[day] = { total: 0, present: 0 };');
L('    byDayMap[day].total++;');
L('    if (r.status === "PRESENT") byDayMap[day].present++;');
L('  }');
L('');
L('  return {');
L('    totalStudents: Object.keys(byStudent).length, totalRecords: total, presentCount: present, absentCount: absent, lateCount: late, excusedCount: excused,');
L('    rate: total > 0 ? Math.round((present / total) * 100) : null,');
L('    byGroup: Object.entries(byGroup).map(([name, v]) => ({ name, rate: v.total > 0 ? Math.round((v.present / v.total) * 100) : null, total: v.total })),');
L('    byDay: Object.entries(byDayMap).map(([day, v]) => ({ day, rate: v.total > 0 ? Math.round((v.present / v.total) * 100) : null })),');
L('    frequentAbsences,');
L('  };');
L('}');
