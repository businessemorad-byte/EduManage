L('// --- Academic ---');
L('');
L('export async function getAcademicReport(organizationId: string, range: DateRange) {');
L('  const assessmentWhere: Record<string, unknown> = { organizationId };');
L('  const df = dateBetween("createdAt", range);');
L('  if (df) Object.assign(assessmentWhere, df);');
L('');
L('  const [assessments, grades] = await Promise.all([');
L('    db.assessment.findMany({ where: assessmentWhere, include: { group: { select: { name: true } }, subject: { select: { name: true } } } }),');
L('    db.grade.findMany({ where: { organizationId }, include: { assessment: { select: { maxScore: true, group: { select: { name: true } }, subject: { select: { name: true } } } } } }),');
L('  ]);');
L('');
L('  const totalAssessments = assessments.length;');
L('  const totalGrades = grades.length;');
L('  const overallAverage = totalGrades > 0 ? Math.round(grades.reduce((sum: number, g: { score: number; assessment: { maxScore: unknown } }) => sum + (g.score / Number(g.assessment.maxScore) * 100), 0) / totalGrades * 100) / 100 : null;');
L('');
L('  const bySubject: Record<string, { total: number; sum: number }> = {};');
L('  for (const g of grades) {');
L('    const subj = g.assessment.subject?.name || "Unassigned";');
L('    if (!bySubject[subj]) bySubject[subj] = { total: 0, sum: 0 };');
L('    bySubject[subj].total++;');
L('    bySubject[subj].sum += g.score / Number(g.assessment.maxScore) * 100;');
L('  }');
L('');
L('  const byGroup: Record<string, { total: number; sum: number }> = {};');
L('  for (const g of grades) {');
L('    const grp = g.assessment.group?.name || "Unassigned";');
L('    if (!byGroup[grp]) byGroup[grp] = { total: 0, sum: 0 };');
L('    byGroup[grp].total++;');
L('    byGroup[grp].sum += g.score / Number(g.assessment.maxScore) * 100;');
L('  }');
L('');
L('  const byMonth: Record<string, { total: number; sum: number }> = {};');
L('  for (const g of grades) {');
L('    const m = new Date(g.createdAt).toISOString().slice(0, 7);');
L('    if (!byMonth[m]) byMonth[m] = { total: 0, sum: 0 };');
L('    byMonth[m].total++;');
L('    byMonth[m].sum += g.score / Number(g.assessment.maxScore) * 100;');
L('  }');
L('');
L('  return {');
L('    totalAssessments, totalResults: totalGrades, overallAverage,');
L('    bySubject: Object.entries(bySubject).map(([name, v]) => ({ name, average: Math.round(v.sum / v.total * 100) / 100, count: v.total })),');
L('    byGroup: Object.entries(byGroup).map(([name, v]) => ({ name, average: Math.round(v.sum / v.total * 100) / 100, count: v.total })),');
L('    byMonth: Object.entries(byMonth).sort().map(([month, v]) => ({ month, average: Math.round(v.sum / v.total * 100) / 100 })),');
L('  };');
L('}');
