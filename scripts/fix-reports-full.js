// Finance
L('// --- Finance ---');
L('');
L('export async function getFinanceReport(organizationId: string, range: DateRange) {');
L('  const [invoices, payments, refunds] = await Promise.all([');
L('    db.invoice.findMany({ where: { organizationId } }),');
L('    db.payment.findMany({ where: { organizationId, status: "COMPLETED" } }),');
L('    db.refund.findMany({ where: { organizationId } }),');
L('  ]);');
L('');
L('  const totalInvoiced = invoices.reduce((s, i) => s + Number(i.totalAmount), 0);');
L('  const totalPaid = payments.reduce((s, p) => s + Number(p.amount), 0);');
L('  const totalRefunded = refunds.reduce((s, r) => s + Number(r.amount), 0);');
L('  const totalOutstanding = invoices.filter(i => ["PENDING", "PARTIAL", "OVERDUE"].includes(i.status)).reduce((s, i) => s + (Number(i.totalAmount) - Number(i.paidAmount)), 0);');
L('  const overdue = invoices.filter(i => i.status === "OVERDUE").reduce((s, i) => s + (Number(i.totalAmount) - Number(i.paidAmount)), 0);');
L('  const collectionRate = totalInvoiced > 0 ? Math.round((totalPaid / totalInvoiced) * 100) : 0;');
L('');
L('  const byMethod: Record<string, number> = {};');
L('  for (const p of payments) { byMethod[p.method] = (byMethod[p.method] || 0) + Number(p.amount); }');
L('');
L('  const byMonth: Record<string, { invoiced: number; paid: number }> = {};');
L('  for (const i of invoices) { const m = new Date(i.createdAt).toISOString().slice(0, 7); if (!byMonth[m]) byMonth[m] = { invoiced: 0, paid: 0 }; byMonth[m].invoiced += Number(i.totalAmount); }');
L('  for (const p of payments) { const m = new Date(p.createdAt).toISOString().slice(0, 7); if (!byMonth[m]) byMonth[m] = { invoiced: 0, paid: 0 }; byMonth[m].paid += Number(p.amount); }');
L('');
L('  return {');
L('    totalInvoiced, totalPaid, totalRefunded, totalOutstanding, overdue, collectionRate,');
L('    byMethod: Object.entries(byMethod).map(([method, amount]) => ({ method, amount })),');
L('    byMonth: Object.entries(byMonth).sort().map(([month, v]) => ({ month, ...v })),');
L('  };');
L('}');
