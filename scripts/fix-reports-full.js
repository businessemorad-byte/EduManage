L('  const totalPaid = paidAgg._sum.amount ?? new Decimal(0);');
L('  const totalOutstanding = (outstandingAgg._sum.totalAmount ?? new Decimal(0)).minus(outstandingAgg._sum.paidAmount ?? new Decimal(0));');
